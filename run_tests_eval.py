    def run_tests(self, data_df, task_name, exe_file, language, compile_result):

        test_cases = data_df.loc[data_df["Task_Name"].eq(task_name), "Tests"].iloc[0]
        try:
            test_cases= ast.literal_eval(test_cases) if isinstance(test_cases, str) else test_cases
        except Exception as e:
            print(f"Error parsing test cases for task {task_name}: {e}")
            return "ERROR: Invalid test cases format", {}


        test_result= "PASSED"
        test_data = {}

        if exe_file and compile_result:

            if isinstance(test_cases, str):
                try:
                    test_cases = ast.literal_eval(test_cases)
                except Exception as e:
                    print(f"Error parsing test cases: {e}")
                    test_data = {}
                    test_result = "ERROR: Invalid test cases format"

                    
            for test in test_cases.keys():

                #print(f"Running test: {test} for task: {task_name}")
                
                single_test = test_cases[test]
                assert_equal = single_test["Assert"]
                test_input = single_test["Input"]
                test_outpot = single_test["Output"]
                
                if assert_equal == "Manual":    
                    test_data[test] = "MANUAL CHECK REQUIRED"
                    test_result = "MANUAL CHECK REQUIRED"
                    continue

                #print("------------------------------------------------")
                #print("LANGUAGE: ", language)
                #print("INPUT: ", test_input)
                #print("OUTPUT: ",test_outpot)
                #print("FILE: ",exe_file)

                cmd = ""
                
                if test_input != "None":
                    input_cmd = [x for x in test_input.split(" ")]
                else: 
                    test_input = None

                if language == "Python":
                    cmd = ["python3", exe_file]
                elif language == "Java":
                    cmd = ["java", exe_file]
                else:
                    cmd = [exe_file]

                if test_input:
                    cmd.extend(input_cmd)

                try:
                #if True:

                    #print("Running command: ", cmd)

                    p_out = subprocess.run(cmd, capture_output=True, text=True, cwd=self.temp_dir, timeout=5)

                    #print("RETURN RESULT: ", p_out)
                    output = p_out.stdout.strip()

                    #print("TEST OUTPUT: ", output)
                    #print("EXPECTED OUTPUT: ", test_outpot)
                    #print([output, test_outpot])

                    output = self.clean_text(output)
                    test_outpot = self.clean_text(test_outpot)
                
                    output = output.upper()
                    test_outpot = test_outpot.upper()


                    if assert_equal == "True":

                        if output == test_outpot:
                            test_data[test] = "PASSED"
                        else:
                            test_data[test] = f"ERROR: {output}, NOT EQUAL TO EXPECTED OUTPUT, {test_outpot}"
                            test_result = "FAILED"

                    elif assert_equal == "False":

                        if output != test_outpot:
                            test_data[test] = "PASSED"
                        else:
                            test_data[test] = f"ERROR: {output}, EQUAL TO FAULTY OUTPUT, {test_outpot}"
                            test_result = "FAILED"

            

                except subprocess.TimeoutExpired:
                    test_result = "FAILED"
                    test_data[test] = f"ERROR: TIMEOUT"

                except Exception as e:
                    test_result = "ERROR"
                    test_data[test] = f"ERROR: {str(e)}"


            print(f"Test results: {test_data}")
            self.reset_dir(self.temp_dir)
        else:
            test_data = {}
            test_result = "ERROR: No program found."

        return test_result, test_data



    def reset_dir(self, dir_path: str | Path) -> None:
        p = Path(dir_path)
        p.mkdir(parents=True, exist_ok=True)

        for child in p.iterdir():
            if child.is_dir() and not child.is_symlink():
                shutil.rmtree(child)
            else:
                child.unlink()



    def calculate_metrics(self, df, eval_file_path, nr_of_tasks):
        df_evaluated_result = pd.DataFrame()
        nr_compiled = 0
        nr_passed_test = 0

        test_cases = pd.read_excel("data/all_tasks_prerun.xlsx")

        for index, row in df.iterrows():
            task_name = row["Task_Name"]
            generated_code = row['Generated_code']
            language = row['Language']

            compile_result_msg, compile_result, found_code, exe_file = self.compile_code(generated_code, language)

            self.store_compiled_result(task_name, compile_result)

            test_result, test_data = self.run_tests(test_cases, task_name, exe_file, language, compile_result)
            #input()

            if compile_result:
                nr_compiled += 1 

            if test_result == "PASSED":
                nr_passed_test += 1

            data = {
                'Task_Name': task_name,
                'Language': language,
                'Model': row['Model'],
                'Task_Description': row['Task_Description'],
                #'Solution': row[language],
                'Generated_code': row['Generated_code'],
                'Markdown_Code': found_code,
                'Compile_Result': compile_result_msg,
                'Test_Result': test_result,
                'Test_Data': test_data
            }

            df_evaluated_result = pd.concat([df_evaluated_result, pd.DataFrame([data])], ignore_index=True)

            if (index + 1) % 5 == 0:
                print(f"Processed {index + 1}/{len(df)} tasks...")

        self.total_score(df_evaluated_result, nr_compiled, nr_of_tasks, nr_passed_test)

        df_evaluated_result.to_csv(eval_file_path, index=False)
        self.read_csv_to_excel(eval_file_path, eval_file_path.replace('.csv', '.xlsx'))
        return nr_compiled         

